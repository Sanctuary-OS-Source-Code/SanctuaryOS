import { useState, useMemo, useEffect } from "react";
import {
  SidePanel,
  DashboardStatTile,
  SidePanelFilterBar,
  UniversalGroup,
  CustomDropdown,
  ActionButton,
  PanelHeaderGroup,
  PanelHeaderButton,
} from "../shared";
import { useLexicon } from "../LexiconContext";
import { SUPPORTED_LEXICON_LANGUAGES } from "../utils/translationEngine";
import type { CreateLexiconOptions } from "../hooks/useMasonFiles";

interface CreateLexiconSidePanelProps {
  isOpen: boolean;
  onClose: () => void;
  onCreate: (options: CreateLexiconOptions) => void;
  isCloudMode?: boolean;
}

type PackCreationGoal = "vocabulary" | "translation";

function slugifyPackId(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .replace(/\.json$/i, "")
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

export default function CreateLexiconSidePanel({
  isOpen,
  onClose,
  onCreate,
  isCloudMode = false,
}: CreateLexiconSidePanelProps) {
  const { t, registry, lexiconMeta } = useLexicon();

  const [goal, setGoal] = useState<PackCreationGoal>("vocabulary");
  const [selectedLangId, setSelectedLangId] = useState<string>("es");
  const [customLangName, setCustomLangName] = useState<string>("");
  const [displayName, setDisplayName] = useState<string>("");
  const [customSlug, setCustomSlug] = useState<string>("");
  const [slugTouched, setSlugTouched] = useState<boolean>(false);
  const [starterPreset, setStarterPreset] = useState<string>("en-default");

  useEffect(() => {
    if (isOpen) {
      setGoal("vocabulary");
      setSelectedLangId("es");
      setCustomLangName("");
      setDisplayName("");
      setCustomSlug("");
      setSlugTouched(false);
      setStarterPreset("en-default");
    }
  }, [isOpen]);

  const languageDropdownOptions = useMemo(() => {
    return [
      ...SUPPORTED_LEXICON_LANGUAGES.map((lang) => ({
        id: lang.id,
        label: `${lang.label} (${lang.nativeLabel})`,
        searchText: `${lang.label} ${lang.nativeLabel} ${lang.id}`,
        icon: t("icon_language", "language"),
      })),
      {
        id: "__custom__",
        label: t("lex_create_custom_lang_opt", "Custom / Constructed Language (e.g. Conlang)"),
        searchText: "custom constructed conlang dialect",
        icon: t("icon_auto_awesome", "auto_awesome"),
      },
    ];
  }, [t]);

  const starterPresetOptions = useMemo(() => {
    const opts: Array<{ id: string; label: string; icon: string }> = [
      {
        id: "en-default",
        label: `${t("lex_studio_preset_std", "Standard")} (Mod • Library • Play Set)`,
        icon: t("icon_check_circle", "check_circle"),
      },
      {
        id: "en-sanctuary",
        label: `${t("lex_studio_preset_sanctuary", "Sanctuary")} (Artifact • Vault • Blueprint)`,
        icon: t("icon_auto_awesome", "auto_awesome"),
      },
    ];
    const seen = new Set(["en-default", "en-sanctuary"]);
    for (const m of lexiconMeta || []) {
      if (m?.id && !seen.has(m.id)) {
        seen.add(m.id);
        opts.push({
          id: m.id,
          label: `${m.name || m.id}${m.badge ? ` (${m.badge})` : ""}`,
          icon: t("icon_translate", "translate"),
        });
      }
    }
    for (const k of Object.keys(registry || {})) {
      if (!seen.has(k)) {
        seen.add(k);
        const name = registry[k]?._meta_name || k;
        opts.push({
          id: k,
          label: String(name),
          icon: t("icon_translate", "translate"),
        });
      }
    }
    return opts;
  }, [lexiconMeta, registry, t]);

  const activeLangMeta = useMemo(
    () => SUPPORTED_LEXICON_LANGUAGES.find((l) => l.id === selectedLangId),
    [selectedLangId]
  );

  const effectiveDisplayName = useMemo(() => {
    if (displayName.trim()) return displayName.trim();
    if (goal === "translation") {
      if (selectedLangId === "__custom__") {
        return customLangName.trim();
      }
      return activeLangMeta?.label || "";
    }
    return "";
  }, [displayName, goal, selectedLangId, customLangName, activeLangMeta]);

  const autoGeneratedSlug = useMemo(() => {
    if (goal === "translation") {
      if (selectedLangId === "__custom__") {
        const cleanCustom = slugifyPackId(customLangName || displayName);
        return cleanCustom ? `xx-${cleanCustom}` : "";
      }
      const prefix = selectedLangId.toLowerCase();
      const customLabelSlug = displayName.trim()
        ? slugifyPackId(displayName)
        : slugifyPackId(activeLangMeta?.label || "pack");
      if (customLabelSlug.startsWith(`${prefix}-`)) return customLabelSlug;
      return `${prefix}-${customLabelSlug || "pack"}`;
    }
    const baseSlug = slugifyPackId(displayName);
    if (!baseSlug) return "";
    if (/^[a-z]{2}-/.test(baseSlug)) return baseSlug;
    return `en-${baseSlug}`;
  }, [goal, selectedLangId, customLangName, displayName, activeLangMeta]);

  const finalFileId = useMemo(() => {
    const raw = slugTouched ? slugifyPackId(customSlug) : autoGeneratedSlug;
    if (!isCloudMode && raw && !/^[a-z]{2}-/i.test(raw)) {
      const langPrefix =
        goal === "translation" && selectedLangId !== "__custom__"
          ? selectedLangId.split("-")[0].toLowerCase()
          : "en";
      return `${langPrefix}-${raw}`;
    }
    return raw;
  }, [slugTouched, customSlug, autoGeneratedSlug, isCloudMode, goal, selectedLangId]);

  const resolvedLangMetaValue = useMemo(() => {
    if (goal === "vocabulary") return "en";
    if (selectedLangId === "__custom__") {
      return customLangName.trim() || "Custom";
    }
    return activeLangMeta?.label || selectedLangId;
  }, [goal, selectedLangId, customLangName, activeLangMeta]);

  const canSubmit = Boolean(effectiveDisplayName && finalFileId);

  const handleSubmit = () => {
    if (!canSubmit) return;
    onCreate({
      fileId: finalFileId,
      displayName: effectiveDisplayName,
      lang: resolvedLangMetaValue,
      starterPreset: goal === "vocabulary" ? starterPreset : undefined,
    });
  };

  return (
    <SidePanel
      isOpen={isOpen}
      onClose={onClose}
      title={t("chameleons_btn_new_lexicon", "New {Lexicon}")}
      subtitle={t("lex_create_subtitle", "Create a vocabulary or language pack")}
      icon={t("icon_translate", "translate")}
      iconColorClass="text-[var(--accent)]"
      widthClass="w-[92vw] md:w-[660px]"
      headerActions={
        <PanelHeaderGroup>
          <PanelHeaderButton
            icon={t("icon_check", "check")}
            variant="accent"
            onClick={handleSubmit}
            disabled={!canSubmit}
            tooltip={t("auto_create", "Create")}
          />
        </PanelHeaderGroup>
      }
    >
      <div className="flex flex-col gap-4 w-full pb-8">
        {/* Step 1: Choose Pack Goal */}
        <UniversalGroup
          title={t("lex_create_step_goal", "1. What kind of {Lexicon} pack are you making?")}
          icon={t("icon_flag", "flag")}
        >
          <div className="flex flex-col gap-3 w-full">
            <SidePanelFilterBar className="sm:grid-cols-2 gap-3">
              <DashboardStatTile
                variant="filter"
                icon={t("icon_auto_awesome", "auto_awesome")}
                label={t("lex_create_goal_vocab_sub", "Same Language • 21 Core Terms")}
                value={t("lex_create_goal_vocab_title", "Vocabulary / Theme")}
                isActive={goal === "vocabulary"}
                onClick={() => {
                  setGoal("vocabulary");
                  if (!slugTouched) setCustomSlug("");
                }}
              />
              <DashboardStatTile
                variant="filter"
                icon={t("icon_translate", "translate")}
                label={t("lex_create_goal_trans_sub", "28+ Languages • 1-Click Translate")}
                value={t("lex_create_goal_trans_title", "Language Translation")}
                isActive={goal === "translation"}
                onClick={() => {
                  setGoal("translation");
                  if (!slugTouched) setCustomSlug("");
                }}
              />
            </SidePanelFilterBar>

            <p className="text-xs font-medium text-[var(--subtext)] leading-relaxed px-1">
              {goal === "vocabulary"
                ? t(
                  "lex_create_goal_vocab_desc",
                  "Rename the 21 Core Terms (such as {Mod}, {Vault}, {Blueprint}, and {Citizen}) to update 95% of the interface automatically while inheriting Standard English for everything else."
                )
                : t(
                  "lex_create_goal_trans_desc",
                  "Translate the interface into another language. Once created, you can run 1-Click Auto-Translate to populate your pack in seconds and refine any string side-by-side."
                )}
            </p>
          </div>
        </UniversalGroup>

        {/* Step 2: Pack Details */}
        <UniversalGroup
          title={t("lex_create_step_details", "2. Pack Identity & Language")}
          icon={t("icon_badge", "badge")}
        >
          <div className="flex flex-col gap-3.5 w-full">
            {goal === "translation" && (
              <div className="flex flex-col gap-1.5 w-full">
                <label className="text-[10px] font-black uppercase tracking-widest text-[var(--subtext)] ml-1">
                  {t("lex_studio_target_lang_lbl", "Target Language")}
                </label>
                <CustomDropdown
                  disableTint={true}
                  searchable={true}
                  value={selectedLangId}
                  options={languageDropdownOptions}
                  onChange={(val: string[]) => {
                    const nextLang = val[0] || "es";
                    setSelectedLangId(nextLang);
                  }}
                />
              </div>
            )}

            {goal === "translation" && selectedLangId === "__custom__" && (
              <div className="flex flex-col gap-1.5 w-full">
                <label className="text-[10px] font-black uppercase tracking-widest text-[var(--subtext)] ml-1">
                  {t("lex_create_custom_lang_lbl", "Language / Dialect Name")}
                </label>
                <input
                  type="text"
                  value={customLangName}
                  onChange={(e) => setCustomLangName(e.target.value)}
                  placeholder={t("lex_create_custom_lang_ph", "e.g. High Elvish, Belter Creole") as string}
                  className="w-full h-11 glass-surface rounded-xl px-4 text-xs font-bold text-[var(--text)] border border-[color-mix(in_srgb,var(--text)_12%,transparent)] focus:outline-none focus:border-[var(--accent)]"
                />
              </div>
            )}

            <div className="flex flex-col gap-1.5 w-full">
              <label className="text-[10px] font-black uppercase tracking-widest text-[var(--subtext)] ml-1">
                {t("label_lexicon_name", "{Lexicon} Display Name")}
              </label>
              <input
                type="text"
                value={displayName}
                onChange={(e) => setDisplayName(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter" && canSubmit) handleSubmit();
                }}
                placeholder={
                  goal === "translation"
                    ? activeLangMeta
                      ? `${activeLangMeta.label} (${activeLangMeta.nativeLabel})`
                      : (t("lex_create_trans_name_ph", "e.g. Spanish (Community)") as string)
                    : (t("lex_create_vocab_name_ph", "e.g. Cozy Community, Tactical RPG") as string)
                }
                className="w-full h-11 glass-surface rounded-xl px-4 text-sm font-bold text-[var(--text)] border border-[color-mix(in_srgb,var(--text)_12%,transparent)] focus:outline-none focus:border-[var(--accent)]"
              />
            </div>

            {goal === "vocabulary" && (
              <div className="flex flex-col gap-1.5 w-full">
                <label className="text-[10px] font-black uppercase tracking-widest text-[var(--subtext)] ml-1">
                  {t("lex_create_starter_vocab_lbl", "Starting Vocabulary")}
                </label>
                <CustomDropdown
                  disableTint={true}
                  value={starterPreset}
                  options={starterPresetOptions}
                  onChange={(val: string[]) => setStarterPreset(val[0] || "en-default")}
                />
              </div>
            )}

            <div className="flex flex-col gap-1.5 w-full pt-1">
              <div className="flex items-center justify-between gap-2 ml-1">
                <label className="text-[10px] font-black uppercase tracking-widest text-[var(--subtext)]">
                  {t("lex_create_file_id_lbl", "File Identifier")}
                </label>
                <span className="text-[10px] font-mono text-[var(--subtext)] opacity-75">
                  {finalFileId ? `${finalFileId}.json` : "pack-id.json"}
                </span>
              </div>
              <input
                type="text"
                value={slugTouched ? customSlug : autoGeneratedSlug}
                onChange={(e) => {
                  setSlugTouched(true);
                  setCustomSlug(e.target.value);
                }}
                onKeyDown={(e) => {
                  if (e.key === "Enter" && canSubmit) handleSubmit();
                }}
                placeholder="en-custom-pack"
                className="w-full h-10 glass-surface rounded-xl px-4 text-xs font-mono font-bold text-[var(--text)] border border-[color-mix(in_srgb,var(--text)_10%,transparent)] focus:outline-none focus:border-[var(--accent)]"
              />
            </div>
          </div>
        </UniversalGroup>

        <div className="flex items-center justify-end gap-2.5 pt-1">
          <ActionButton
            variant="glass"
            onClick={onClose}
            className="!h-10 !px-4 !text-xs !rounded-xl"
          >
            {t("cancel", "Cancel")}
          </ActionButton>
          <ActionButton
            variant="accent"
            icon={t("icon_arrow_forward", "arrow_forward")}
            disabled={!canSubmit}
            onClick={handleSubmit}
            className="!h-10 !px-5 !text-xs !rounded-xl"
          >
            {t("lex_create_open_studio_btn", "Create & Open Studio")}
          </ActionButton>
        </div>
      </div>
    </SidePanel>
  );
}

