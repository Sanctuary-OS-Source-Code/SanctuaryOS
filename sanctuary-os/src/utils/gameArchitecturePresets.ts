export const resolvePresetForGameId = (id?: string | null): Record<string, any> => {
  const clean = String(id || "").toLowerCase().replace(/[^a-z0-9]/g, "");
  if (!clean || isSims4SchemaId(id)) return GAME_ARCHITECTURE_PRESETS.sims4;
  if (clean.includes("gtav") || clean.includes("gta5") || clean.includes("grandtheftauto")) {
    return GAME_ARCHITECTURE_PRESETS.gtav;
  }
  if (clean.includes("wwe2k") || clean.includes("wwe")) {
    return GAME_ARCHITECTURE_PRESETS.wwe2k;
  }
  if (clean.includes("skyrim") || clean.includes("fallout") || clean.includes("starfield") || clean.includes("oblivion")) {
    return GAME_ARCHITECTURE_PRESETS.skyrim;
  }
  if (clean.includes("cyberpunk") || clean.includes("cp2077")) {
    return GAME_ARCHITECTURE_PRESETS.cyberpunk2077;
  }
  if (clean.includes("bg3") || clean.includes("baldursgate")) {
    return GAME_ARCHITECTURE_PRESETS.bg3;
  }
  if (clean.includes("stardew") || clean.includes("smapi")) {
    return GAME_ARCHITECTURE_PRESETS.stardew;
  }
  return GAME_ARCHITECTURE_PRESETS.universal;
};

