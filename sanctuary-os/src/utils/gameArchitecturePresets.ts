export const isSims4SchemaId = (id?: string | null): boolean => {
  const clean = String(id || "").toLowerCase().trim();
  return (
    !clean ||
    clean === "sims4" ||
    clean === "the-sims-4" ||
    clean === "the_sims_4" ||
    clean === "ts4" ||
    clean === "default" ||
    clean === "default_schema"
  );
};

